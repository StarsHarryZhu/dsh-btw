/**
 * A translator over the bundled dictionaries, for components rendered without a host `t`.
 * @param key - the message key.
 * @param params - `{name}` substitutions.
 * @returns the Chinese text, or the key.
 */
export function fallbackT(key: string, params?: Record<string, unknown>): string {
  return (zh[key] ?? key).replace(/\{(\w+)\}/gu, (match, name: string) => String(params?.[name] ?? match))
}
